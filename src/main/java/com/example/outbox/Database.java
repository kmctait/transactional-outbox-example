package com.example.outbox;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * An in-memory H2 database plus the schema used by the demo.
 *
 * <p>Every component opens its own connection, so the transaction boundaries are
 * real: the order service really does commit the business row and the outbox row
 * in one local transaction, and the relay really does read from a different
 * connection.</p>
 */
final class Database implements AutoCloseable {

    private static final List<String> SCHEMA = List.of(
            """
            CREATE TABLE orders (
                id          VARCHAR(36) PRIMARY KEY,
                customer_id VARCHAR(64) NOT NULL,
                total       DECIMAL(10, 2) NOT NULL,
                status      VARCHAR(16) NOT NULL,
                created_at  TIMESTAMP NOT NULL
            )
            """,
            """
            CREATE TABLE outbox (
                id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                message_id     VARCHAR(36) NOT NULL UNIQUE,
                aggregate_type VARCHAR(64) NOT NULL,
                aggregate_id   VARCHAR(36) NOT NULL,
                event_type     VARCHAR(64) NOT NULL,
                payload        CLOB NOT NULL,
                created_at     TIMESTAMP NOT NULL,
                published_at   TIMESTAMP
            )
            """,
            """
            CREATE INDEX idx_outbox_pending ON outbox (published_at, id)
            """,
            """
            CREATE TABLE shipments (
                order_id   VARCHAR(36) PRIMARY KEY,
                status     VARCHAR(16) NOT NULL,
                created_at TIMESTAMP NOT NULL
            )
            """,
            """
            CREATE TABLE processed_messages (
                message_id   VARCHAR(36) PRIMARY KEY,
                processed_at TIMESTAMP NOT NULL
            )
            """);

    /** Work executed inside a single database transaction. */
    @FunctionalInterface
    interface SqlWork<T> {
        T run(Connection connection) throws SQLException;
    }

    private final String url;

    private Database(String url) {
        this.url = url;
    }

    /** Starts a fresh, isolated in-memory database and applies the schema. */
    static Database start() throws SQLException {
        // A unique name per instance keeps tests independent; DB_CLOSE_DELAY=-1 keeps
        // the database alive while individual connections are opened and closed.
        Database database = new Database("jdbc:h2:mem:outbox-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        database.createSchema();
        return database;
    }

    private void createSchema() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            for (String ddl : SCHEMA) {
                statement.execute(ddl);
            }
        }
    }

    Connection connection() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    /**
     * Runs {@code work} in a transaction: commits if it returns normally, rolls
     * back if it throws. The rollback also discards any outbox rows written by
     * the same unit of work.
     */
    <T> T inTransaction(SqlWork<T> work) throws SQLException {
        try (Connection connection = connection()) {
            connection.setAutoCommit(false);
            try {
                T result = work.run(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                connection.rollback();
                throw e;
            }
        }
    }

    /** Convenience query helper used by the demo and the tests. */
    int queryInt(String sql, Object... parameters) throws SQLException {
        try (Connection connection = connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, parameters);
            try (ResultSet resultSet = statement.executeQuery()) {
                resultSet.next();
                return resultSet.getInt(1);
            }
        }
    }

    static void bind(PreparedStatement statement, Object... parameters) throws SQLException {
        for (int i = 0; i < parameters.length; i++) {
            Object parameter = parameters[i];
            if (parameter instanceof Instant instant) {
                statement.setTimestamp(i + 1, Timestamp.from(instant));
            } else {
                statement.setObject(i + 1, parameter);
            }
        }
    }

    @Override
    public void close() throws SQLException {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("SHUTDOWN");
        }
    }
}
